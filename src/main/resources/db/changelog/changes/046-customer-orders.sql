-- Customer orders ("Поръчки") for sold cars. The car's main data is copied into the order when the order is made
-- (or gets another car), so the order keeps its history when the car is deleted by hand (car_id is then null).
CREATE TABLE customer_order (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id             BIGINT REFERENCES car (id) ON DELETE SET NULL,
    car_title          VARCHAR(255),
    car_slug           VARCHAR(255),
    car_make           VARCHAR(100),
    car_model          VARCHAR(100),
    car_year           INTEGER,
    car_mileage_km     INTEGER,
    car_source         VARCHAR(20),
    car_source_url     VARCHAR(2000),
    car_source_ref     VARCHAR(255),
    car_price_eur      NUMERIC(14, 2),
    customer_name      VARCHAR(200),
    customer_phone     VARCHAR(50),
    customer_email     VARCHAR(200),
    customer_address   VARCHAR(500),
    customer_id_number VARCHAR(20),
    company_name       VARCHAR(200),
    company_eik        VARCHAR(20),
    vin                VARCHAR(30),
    agreed_price_eur   NUMERIC(14, 2),
    deposit_eur        NUMERIC(14, 2),
    status             VARCHAR(20)  NOT NULL DEFAULT 'CONTRACT_SIGNED',
    container_number   VARCHAR(30),
    contract_date      DATE,
    notes              TEXT,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by         VARCHAR(100)
);

CREATE INDEX idx_customer_order_car ON customer_order (car_id);
CREATE INDEX idx_customer_order_created ON customer_order (created_at DESC, id DESC);
-- one active (not cancelled) order per car
CREATE UNIQUE INDEX uq_customer_order_active_car ON customer_order (car_id)
    WHERE car_id IS NOT NULL AND status <> 'CANCELLED';

-- An order's documents (invoices, contract, bill of lading, customs): the rows only; the files' storage comes later
-- (storage_key = where the bytes are kept).
CREATE TABLE order_document (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT        NOT NULL REFERENCES customer_order (id) ON DELETE CASCADE,
    kind         VARCHAR(30)   NOT NULL,
    title        VARCHAR(200),
    file_name    VARCHAR(255)  NOT NULL,
    content_type VARCHAR(100),
    size_bytes   BIGINT,
    storage_key  VARCHAR(500),
    uploaded_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    uploaded_by  VARCHAR(100)
);

CREATE INDEX idx_order_document_order ON order_document (order_id, id);
