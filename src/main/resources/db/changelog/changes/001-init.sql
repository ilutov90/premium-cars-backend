--changeset premiumcars:001-car
CREATE TABLE car (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug             VARCHAR(255)  NOT NULL UNIQUE,
    status           VARCHAR(20)   NOT NULL,
    source           VARCHAR(20)   NOT NULL,
    source_url       VARCHAR(2000) UNIQUE,
    source_ref       VARCHAR(255),
    title            VARCHAR(255)  NOT NULL,
    make             VARCHAR(100),
    model            VARCHAR(100),
    trim_level       VARCHAR(255),
    model_year       INTEGER,
    mileage_km       INTEGER,
    fuel_type        VARCHAR(20),
    transmission     VARCHAR(20),
    body_type        VARCHAR(100),
    engine           VARCHAR(100),
    power_hp         INTEGER,
    color            VARCHAR(50),
    description      TEXT,
    specs            JSONB,
    source_price     NUMERIC(14, 2),
    source_currency  VARCHAR(3),
    shipping_eur     NUMERIC(12, 2),
    margin_eur       NUMERIC(12, 2),
    extra_duty_rate  NUMERIC(6, 4),
    total_price_eur  NUMERIC(14, 2),
    created_at       TIMESTAMPTZ   NOT NULL,
    updated_at       TIMESTAMPTZ   NOT NULL,
    published_at     TIMESTAMPTZ
);

CREATE INDEX idx_car_status_published ON car (status, published_at DESC);
CREATE INDEX idx_car_make ON car (lower(make));
CREATE INDEX idx_car_total_price ON car (total_price_eur);

--changeset premiumcars:001-car-image
CREATE TABLE car_image (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id        BIGINT        NOT NULL REFERENCES car (id) ON DELETE CASCADE,
    storage_path  VARCHAR(500)  NOT NULL,
    source_url    VARCHAR(2000),
    position      INTEGER       NOT NULL
);

CREATE INDEX idx_car_image_car ON car_image (car_id, position);

--changeset premiumcars:001-inquiry
CREATE TABLE inquiry (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id      BIGINT REFERENCES car (id) ON DELETE SET NULL,
    name        VARCHAR(255) NOT NULL,
    phone       VARCHAR(40),
    email       VARCHAR(200),
    message     TEXT,
    status      VARCHAR(20)  NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL
);

CREATE INDEX idx_inquiry_status_created ON inquiry (status, created_at DESC);
