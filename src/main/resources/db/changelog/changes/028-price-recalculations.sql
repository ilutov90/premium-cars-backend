--changeset premiumcars:028-price-recalculations
-- Price recalculations started by hand (admin panel "Цени"): every car of a site or of all sites, from the FOB price
-- kept at the import (STORED) or read again from the source's listing (SOURCE). The report keeps the cars whose
-- price changed (and those whose listing could not be read) with where each one was posted, so the posts can be
-- updated by hand.

CREATE TABLE price_recalc_run (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope        VARCHAR(20)  NOT NULL,          -- ALL or a CarSource
    mode         VARCHAR(20)  NOT NULL,          -- STORED or SOURCE
    status       VARCHAR(20)  NOT NULL,          -- RUNNING, DONE, FAILED
    started_by   VARCHAR(50),
    started_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    finished_at  TIMESTAMPTZ,
    total        INTEGER      NOT NULL DEFAULT 0,
    processed    INTEGER      NOT NULL DEFAULT 0,
    changed      INTEGER      NOT NULL DEFAULT 0,
    fixed_price  INTEGER      NOT NULL DEFAULT 0, -- cars with a final price set by hand: kept
    failed       INTEGER      NOT NULL DEFAULT 0, -- SOURCE: the listing could not be read
    message      VARCHAR(1000)
);

CREATE TABLE price_recalc_item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id           BIGINT        NOT NULL REFERENCES price_recalc_run (id) ON DELETE CASCADE,
    car_id           BIGINT        REFERENCES car (id) ON DELETE SET NULL,
    kind             VARCHAR(20)   NOT NULL,      -- CHANGED or FAILED
    title            VARCHAR(300),
    slug             VARCHAR(200),
    car_status       VARCHAR(20),
    source           VARCHAR(20),
    source_url       VARCHAR(1000),
    old_price_eur    NUMERIC(12, 2),
    new_price_eur    NUMERIC(12, 2),
    old_source_price NUMERIC(14, 2),
    new_source_price NUMERIC(14, 2),
    source_currency  VARCHAR(3),
    note             VARCHAR(1000),
    posted           JSONB         NOT NULL DEFAULT '[]'
);
CREATE INDEX idx_price_recalc_item_run ON price_recalc_item (run_id, kind, id);
