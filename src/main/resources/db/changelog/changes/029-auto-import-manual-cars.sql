--changeset premiumcars:029-auto-import-manual-cars
-- The nightly run also checks the autowini and guazi cars added by hand (or of makes no longer imported): their
-- make is searched at the source without the import's filters, and a car whose listing is missing in 2 runs in a
-- row is hidden (REMOVED) like the imported ones. Every car a run hides goes to the run's report with where it was
-- posted (Facebook, Instagram, Viber, mobile.bg), to take those posts down by hand.

ALTER TABLE auto_import_run
    ADD COLUMN manual_checked INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN manual_gone    INTEGER NOT NULL DEFAULT 0;

CREATE TABLE auto_import_manual_check (
    car_id        BIGINT      PRIMARY KEY REFERENCES car (id) ON DELETE CASCADE,
    missed_passes INTEGER     NOT NULL DEFAULT 0,
    last_checked  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE auto_import_removed (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id     BIGINT        REFERENCES auto_import_run (id) ON DELETE CASCADE,
    car_id     BIGINT        REFERENCES car (id) ON DELETE SET NULL,
    source     VARCHAR(20)   NOT NULL,
    title      VARCHAR(300),
    slug       VARCHAR(200),
    source_url VARCHAR(1000),
    manual     BOOLEAN       NOT NULL,
    posted     JSONB         NOT NULL DEFAULT '[]',
    removed_at TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_auto_import_removed_run ON auto_import_removed (run_id);
