--changeset premiumcars:018-inquiry-attribution
-- Where an inquiry came from: what the customer picked in "Откъде научихте за нас?" (HeardFrom name) and the
-- UTM parameters / landing page / referring site of their first visit, kept by the browser until they sent it.
ALTER TABLE inquiry
    ADD COLUMN heard_from   VARCHAR(30),
    ADD COLUMN utm_source   VARCHAR(100),
    ADD COLUMN utm_medium   VARCHAR(100),
    ADD COLUMN utm_campaign VARCHAR(100),
    ADD COLUMN utm_content  VARCHAR(100),
    ADD COLUMN landing_path VARCHAR(300),
    ADD COLUMN referrer     VARCHAR(200);

CREATE INDEX idx_inquiry_created ON inquiry (created_at);

--changeset premiumcars:018-delivered-car
-- "Доставени коли": cars handed over to customers, with the customer's words and a photo, shown on the site once
-- an admin publishes them (only with the customer's consent).
CREATE TABLE delivered_car (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id        BIGINT REFERENCES car (id) ON DELETE SET NULL,
    car_title     VARCHAR(200) NOT NULL,
    customer_name VARCHAR(100) NOT NULL,
    city          VARCHAR(100),
    quote         TEXT,
    delivered_on  DATE,
    photo_path    VARCHAR(500),
    consent       BOOLEAN      NOT NULL DEFAULT false,
    published     BOOLEAN      NOT NULL DEFAULT false,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT delivered_car_published_needs_consent CHECK (NOT published OR consent)
);

CREATE INDEX idx_delivered_car_public ON delivered_car (published, delivered_on DESC NULLS LAST, id DESC);
