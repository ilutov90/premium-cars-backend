-- Inquiries and orders tied together: an order may come from an inquiry ("Свързахме се" makes a potential order,
-- status LEAD). A LEAD keeps the cars offered to the customer in order_candidate_car: they are neither marked sold
-- nor kept from the automatic import; the chosen one becomes the order's car (then SOLD, as before).
ALTER TABLE customer_order ADD COLUMN inquiry_id BIGINT REFERENCES inquiry (id) ON DELETE SET NULL;
ALTER TABLE customer_order ADD COLUMN next_contact_at TIMESTAMPTZ;
ALTER TABLE customer_order ADD COLUMN lost_reason VARCHAR(30);
CREATE UNIQUE INDEX uq_customer_order_inquiry ON customer_order (inquiry_id) WHERE inquiry_id IS NOT NULL;
CREATE INDEX idx_customer_order_next_contact ON customer_order (next_contact_at) WHERE next_contact_at IS NOT NULL;

-- a potential order does not hold its car
DROP INDEX uq_customer_order_active_car;
CREATE UNIQUE INDEX uq_customer_order_active_car ON customer_order (car_id)
    WHERE car_id IS NOT NULL AND status NOT IN ('CANCELLED', 'LEAD');

-- The cars offered to the customer of an order, with what they were when added (the car may be deleted later).
CREATE TABLE order_candidate_car (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT        NOT NULL REFERENCES customer_order (id) ON DELETE CASCADE,
    car_id      BIGINT        REFERENCES car (id) ON DELETE SET NULL,
    car_title   VARCHAR(255),
    car_slug    VARCHAR(255),
    car_price_eur NUMERIC(14, 2),
    cover_url   VARCHAR(2000),
    added_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    added_by    VARCHAR(100)
);
CREATE INDEX idx_order_candidate_order ON order_candidate_car (order_id, id);
CREATE UNIQUE INDEX uq_order_candidate_car ON order_candidate_car (order_id, car_id) WHERE car_id IS NOT NULL;

-- What was said with the customer: calls, Viber, e-mails, meetings, notes; newest first in the admin panel.
CREATE TABLE order_contact (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT        NOT NULL REFERENCES customer_order (id) ON DELETE CASCADE,
    kind        VARCHAR(20)   NOT NULL,
    body        TEXT          NOT NULL,
    happened_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by  VARCHAR(100),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_order_contact_order ON order_contact (order_id, happened_at DESC, id DESC);
