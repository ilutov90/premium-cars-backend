--changeset premiumcars:023-auto-import
-- Automatic import (October 2026): every night the search results of autowini and guazi for the chosen makes, years
-- and filters are listed; new listings are imported and published, listings gone from the source are hidden
-- (status REMOVED, car.removed_at) and deleted 30 days later. Everything is off until an admin turns it on.

ALTER TABLE car ADD COLUMN removed_at TIMESTAMPTZ;
CREATE INDEX idx_car_removed ON car (removed_at) WHERE removed_at IS NOT NULL;

-- the main switch (one row)
CREATE TABLE auto_import_state (
    id         SMALLINT    PRIMARY KEY CHECK (id = 1),
    enabled    BOOLEAN     NOT NULL DEFAULT false,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
INSERT INTO auto_import_state (id, enabled) VALUES (1, false);

-- one row per source site: its own switch and filters ({"inspected","actualMileage"} for autowini, {"grades"} for guazi)
CREATE TABLE auto_import_source (
    source     VARCHAR(20) PRIMARY KEY,
    enabled    BOOLEAN     NOT NULL DEFAULT false,
    filters    JSONB       NOT NULL DEFAULT '{}',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- the makes to import: code = the source's make id, models = chosen models [{"code","name"}] (empty = all)
CREATE TABLE auto_import_brand (
    source    VARCHAR(20)  NOT NULL REFERENCES auto_import_source (source),
    code      VARCHAR(40)  NOT NULL,
    name      VARCHAR(100) NOT NULL,
    enabled   BOOLEAN      NOT NULL DEFAULT true,
    year_from INTEGER      NOT NULL CHECK (year_from BETWEEN 1990 AND 2100),
    models    JSONB        NOT NULL DEFAULT '[]',
    PRIMARY KEY (source, code)
);

-- the sources' own lists of makes and models (refreshed by the nightly run and on demand)
CREATE TABLE auto_import_catalog (
    source     VARCHAR(20)  NOT NULL,
    code       VARCHAR(40)  NOT NULL,
    name       VARCHAR(100) NOT NULL,
    models     JSONB,
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (source, code)
);

-- every listing the nightly run found: QUEUED (to import), IMPORTED (car_id), FAILED (gave up for now)
CREATE TABLE auto_import_listing (
    source        VARCHAR(20)    NOT NULL,
    listing_id    VARCHAR(60)    NOT NULL,
    url           VARCHAR(1000)  NOT NULL,
    brand_code    VARCHAR(40)    NOT NULL,
    title         VARCHAR(300),
    price         NUMERIC(12, 2),
    state         VARCHAR(20)    NOT NULL,
    attempts      INTEGER        NOT NULL DEFAULT 0,
    last_error    VARCHAR(1000),
    missed_passes INTEGER        NOT NULL DEFAULT 0,
    car_id        BIGINT         REFERENCES car (id) ON DELETE SET NULL,
    first_seen    TIMESTAMPTZ    NOT NULL DEFAULT now(),
    last_seen     TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),
    PRIMARY KEY (source, listing_id)
);
CREATE INDEX idx_auto_import_listing_state ON auto_import_listing (state, source, first_seen);
CREATE INDEX idx_auto_import_listing_car ON auto_import_listing (car_id);

-- one row per run (nightly, "run now" or a dry run)
CREATE TABLE auto_import_run (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source         VARCHAR(20)   NOT NULL,
    dry_run        BOOLEAN       NOT NULL,
    status         VARCHAR(20)   NOT NULL,
    started_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    finished_at    TIMESTAMPTZ,
    found          INTEGER       NOT NULL DEFAULT 0,
    new_count      INTEGER       NOT NULL DEFAULT 0,
    gone_count     INTEGER       NOT NULL DEFAULT 0,
    returned_count INTEGER       NOT NULL DEFAULT 0,
    brands         JSONB         NOT NULL DEFAULT '[]',
    message        VARCHAR(2000)
);
CREATE INDEX idx_auto_import_run_started ON auto_import_run (started_at DESC);

